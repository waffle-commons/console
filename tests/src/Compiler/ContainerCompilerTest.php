    public function testNullableUnionWithNoRegisteredMemberThrowsLikeAutowire(): void
    {
        // A nullable union (A|B|null) with no default and no registered member.
        // Autowire's union resolver does NOT honour nullability — with no candidate
        // and no default it THROWS. The compiled wiring must mirror that throw
