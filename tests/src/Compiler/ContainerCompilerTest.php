        $runtime = new FakeRuntimeContainer();
        $runtime->set(NullableUnionDependentService::class, NullableUnionDependentService::class);

        $runtimeThrew = false;
        try {
            $runtime->get(NullableUnionDependentService::class);
        } catch (RuntimeException) {
            $runtimeThrew = true;
        }
        static::assertTrue(
            $runtimeThrew,
            'baseline: Autowire throws for an unregistered nullable union with no default',
        );

        $input = new FakeRuntimeContainer();
