    /**
     * Mirrors `ContainerCompiler::quote()`'s backslash doubling so a match-arm key
     * can be matched verbatim in the generated source.
     */
    private function sourceQuotedKey(string $fqcn): string
    {
        return str_replace('\\', '\\\\', $fqcn);
    }

    /**
     * Reads a compiled container's private `$instances` memo by reflection.
     *
     * @return array<string, mixed>
     */
    private function memoOf(CompiledContainerInterface $compiled): array
    {
        $memo = new ReflectionObject($compiled)
            ->getProperty('instances')
            ->getValue($compiled);
        if (!is_array($memo)) {
            static::fail('the compiled memo must be an array');
        }

        /** @var array<string, mixed> $memo */
        return $memo;
    }

    /**
     * @return list<string> The parity-oracle service ids.
     */
    private function parityIds(): array
    {
        return [
            ResetCountingService::class,
            LeafService::class,
            'factory.resettable',
            'factory.plain',
            'prebuilt.resettable',
            'prebuilt.plain',
        ];
    }

    /**
     * Registers the parity-oracle definition set: an inlined class, closure
     * factories, and pre-registered objects — each in a Resettable and a
     * non-Resettable variant. Objects are created per container so the reset
     * counts of the two containers under comparison stay independent.
     */
    private function seedParity(FakeRuntimeContainer $container): void
    {
        $container->set(ResetCountingService::class, ResetCountingService::class);
        $container->set(LeafService::class, LeafService::class);
        $container->set('factory.resettable', static fn(): ResetCountingService => new ResetCountingService());
        $container->set('factory.plain', static fn(): LeafService => new LeafService());
        $container->set('prebuilt.resettable', new ResetCountingService());
        $container->set('prebuilt.plain', new LeafService());
    }

    /**
     * Runs $cycles get()/reset() request cycles against a parity-seeded container
     * and returns the per-id reset counts (null for non-resettable services),
     * asserting every instance keeps its identity across the cycles.
     *
     * @return array<string, int|null>
     */
    private function exerciseResetCycles(ContainerInterface $container, int $cycles): array
    {
        $first = [];
        foreach ($this->parityIds() as $id) {
            $first[$id] = $container->get($id);
        }

        for ($cycle = 0; $cycle < $cycles; $cycle++) {
            $container->reset();
            foreach ($this->parityIds() as $id) {
                static::assertSame(
                    $first[$id],
                    $container->get($id),
                    sprintf('"%s" must keep its identity across reset cycles', $id),
                );
            }
        }

        $counts = [];
        foreach ($first as $id => $instance) {
            $counts[$id] = $instance instanceof ResetCountingService ? $instance->resets : null;
        }

        return $counts;
    }

    /**
     * Captures id → {fqcn, args:[recursive signatures]} for each id, walking the
     * BUILT objects' constructor arguments by reflection. FQCN-normalised: object
     * identity is irrelevant, only concrete classes + wiring shape.
     *
     * @param list<string> $ids
     * @return array<string, array{fqcn: string, args: array<string, mixed>}>
     */
    private function signatureOf(ContainerInterface $container, array $ids): array
    {
        $signature = [];
        foreach ($ids as $id) {
            $instance = $container->get($id);
            $signature[$id] = $this->describe($instance);
        }

        return $signature;
    }

    /**
     * @return array{fqcn: string, args: array<string, mixed>}
     */
    private function describe(mixed $instance): array
    {
        if (!is_object($instance)) {
            return ['fqcn' => get_debug_type($instance), 'args' => []];
        }

        $reflection = new ReflectionObject($instance);
        $args = [];
        foreach ($reflection->getProperties() as $property) {
            $value = $property->getValue($instance);
            $args[$property->getName()] = is_object($value)
                ? $this->describe($value)
                : ['fqcn' => get_debug_type($value), 'args' => []];
        }

        return ['fqcn' => $instance::class, 'args' => $args];
    }

    /**
     * Compiles $input to source, writes it to a temp artifact, requires it, and
     * returns a CompiledContainer composing a FRESH (re-seeded) runtime container.
     */
    private function loadCompiledContainer(FakeRuntimeContainer $input, string $tag): CompiledContainerInterface
    {
        $namespace = 'WaffleTests\\Commons\\Console\\Compiler\\Generated';
        $className = 'CompiledContainer' . $tag;

        $source = new ContainerCompiler()->compile($input, $namespace, $className, FakeRuntimeContainer::class);

        $file = sys_get_temp_dir() . '/' . $className . '_' . uniqid() . '.php';
        file_put_contents($file, $source);
        $this->artifacts[] = $file;

        require $file;

        // The generated container composes the SAME (already-seeded) runtime
        // container the compiler inspected — its closures/objects live there.
        $fqcn = $namespace . '\\' . $className;
        $instance = new $fqcn($input);
        static::assertInstanceOf(CompiledContainerInterface::class, $instance);

        return $instance;
    }
