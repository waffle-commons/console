        $compiled = $this->loadCompiledContainer($input, 'NullableUnion');

        // The emitted source resolves the first union candidate (which throws for an
        // unregistered id) — NOT a `null` short-circuit.
        $this->expectException(RuntimeException::class);
        $compiled->get(NullableUnionDependentService::class);
    }

